# Builds the boss and enemy shuffle tables from an unpacked BLACK SOULS II Data folder
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from rbmarshal import load, text

ROOT = Path(__file__).resolve().parent.parent
DATA = Path(sys.argv[1])
OUT = ROOT / "apworld" / "src" / "black_souls2" / "Shuffle.py"

# boss troops kept in place because their fights carry story scripting or are not real arenas
FIXED_BOSSES = {30, 31, 32, 91, 174, 179, 181, 183, 210, 220, 222, 270, 331, 373, 544, 568, 569, 614, 616}
# story driven groups found in encounter tables
FIXED_ENEMIES = set()
DLC_TROOP_START = 500
SAFE_EFFECTS = {121, 117, 129}
SAFE_SWITCHES = {24}

troops = load(DATA / "Troops.rvdata2")
enemies = load(DATA / "Enemies.rvdata2")
mapinfo = load(DATA / "MapInfos.rvdata2")
script = (ROOT / "Archipelago_Combined.rb").read_text(encoding="utf-8")


def ruby_hash_keys(name):
    block = script[script.index(name + " = {"):]
    block = block[:block.index("\n    }")]
    return [int(x) for x in re.findall(r"^\s*(\d+)\s*=>", block, re.M)]


def stats(tid):
    mem = [enemies[m["enemy_id"]] for m in troops[tid]["members"]]
    if not mem:
        return None
    return dict(troop=tid, name=text(troops[tid]["name"]).strip(), hp=sum(e["params"][0] for e in mem),
                atk=max(max(e["params"][2], e["params"][4]) for e in mem), dlc=tid >= DLC_TROOP_START)


def side_effects(tid):
    found = set()
    for page in troops[tid]["pages"]:
        for c in page["list"]:
            if c["code"] == 121:
                found |= {f"sw{s}" for s in range(c["parameters"][0], c["parameters"][1] + 1)} - {f"sw{s}" for s in SAFE_SWITCHES}
            elif c["code"] in (201, 301, 340, 353, 126, 127, 128, 355):
                found.add(f"c{c['code']}")
    return found


boss_ids = ruby_hash_keys("BOSS_SOUL_TROOP_TRIGGERS")
bosses = [stats(t) for t in boss_ids if t not in FIXED_BOSSES]
bosses = [b for b in bosses if b]

encounter = set()
for mid in mapinfo:
    for enc in load(DATA / f"Map{mid:03d}.rvdata2")["encounter_list"] or []:
        encounter.add(enc["troop_id"])
pool_block = script[script.index("REGION_TROOP_POOLS = {"):].split("\n", 1)[0]
encounter |= {int(x) for x in re.findall(r"(\d+)", pool_block.split("=", 1)[1]) if int(x) < len(troops)}
skip = set(boss_ids) | FIXED_ENEMIES
enemy_rows = []
for tid in sorted(encounter - skip):
    if tid <= 0 or tid >= len(troops) or troops[tid] is None or side_effects(tid):
        continue
    row = stats(tid)
    if row and row["hp"] > 0:
        enemy_rows.append(row)

lines = ["# Generated by tools/build_shuffle_tables.py", "", "BOSSES = ["]
lines += [f"    {json.dumps(b, ensure_ascii=False)}," for b in bosses]
lines += ["]", "", "ENEMIES = ["]
lines += [f"    {json.dumps(e, ensure_ascii=False)}," for e in enemy_rows]
lines += ["]", ""]
OUT.write_text("\n".join(lines).replace("true", "True").replace("false", "False"), encoding="utf-8")
print(len(bosses), "bosses", len(enemy_rows), "enemy groups", sum(b["dlc"] for b in bosses), "dlc bosses")
